    /// Convert camelCase to snake_case for database field names
    fn camel_to_snake_case(&self, input: &str) -> String {
        let mut result = String::new();
        let mut chars = input.chars().peekable();
        
        while let Some(ch) = chars.next() {
            if ch.is_uppercase() && !result.is_empty() {
                result.push('_');
            }
            result.push(ch.to_lowercase().next().unwrap());
        }
        
        result
    }
    
    /// Generate complete Hasura v2 style resolver implementation
    pub fn generate_resolvers(&self, models: &[Model]) -> Result<String> {
        let mut resolvers = String::new();
        
        // Add resolver header and imports
        resolvers.push_str(&self.generate_header());
        
        // Generate Query resolvers
        resolvers.push_str(&self.generate_query_resolvers(models)?);
        
        // Generate Mutation resolvers  
        resolvers.push_str(&self.generate_mutation_resolvers(models)?);
        
        // Generate resolver registration
        resolvers.push_str(&self.generate_resolver_registration(models)?);
        
        Ok(resolvers)
    }
    
    /// Generate header with imports and basic setup
    fn generate_header(&self) -> String {
        format!(r#"// Auto-generated Hasura v2 Style GraphQL resolvers
// DO NOT EDIT - This file is automatically generated

use async_graphql::{{Context, Object, FieldResult, ID, EmptySubscription}};
use sqlx::PgPool;
use serde_json::Value;

use super::models::*;

// Hasura v2 style resolvers
pub struct Query;
pub struct Mutation;

"#)
    }
    
    /// Generate Query resolvers for all models following Hasura v2 conventions
    fn generate_query_resolvers(&self, models: &[Model]) -> Result<String> {
        let mut query_impl = String::new();
        
        query_impl.push_str("#[Object]\nimpl Query {\n");
        
        for model in models {
            // Skip Block types and enum types
            if model.name.ends_with("Block") || model.fields.contains_key("_enum_type") {
                continue;
            }
            
            let model_name = &model.name;
            let model_lower = model_name.to_lowercase();
            let table_name = format!("{}s", model_lower); // Pluralize table name
            
            // Generate list query: users, deals, companies, contacts
            query_impl.push_str(&self.generate_list_query(model)?);
            
            // Generate single query by primary key: user_by_pk, deal_by_pk
            query_impl.push_str(&self.generate_by_pk_query(model)?);
            
            // Generate aggregate query: users_aggregate, deals_aggregate
            query_impl.push_str(&self.generate_aggregate_query(model)?);
        }
        
        query_impl.push_str("}\n\n");
        Ok(query_impl)
    }
    
    /// Generate list query following Hasura v2 conventions
    fn generate_list_query(&self, model: &Model) -> Result<String> {
        let model_name = &model.name;
        let model_lower = model_name.to_lowercase();
        let table_name = format!("{}s", model_lower);
        
        Ok(format!(
            r#"    /// Query {table_name} with Hasura v2 style filtering and ordering
    async fn {table_name}(
        &self,
        ctx: &Context<'_>,
        where_: Option<{model_name}BoolExp>,
        order_by: Option<Vec<{model_name}OrderBy>>,
        limit: Option<i32>,
        offset: Option<i32>,
        distinct_on: Option<Vec<{model_name}SelectColumn>>,
    ) -> FieldResult<Vec<{model_name}>> {{
        let pool = ctx.data::<PgPool>()?;
        
        // Build base query
        let mut query = format!("SELECT * FROM {model_lower}");
        let mut params: Vec<Box<dyn sqlx::Encode<'_, sqlx::Postgres> + Send + Sync>> = Vec::new();
        let mut param_count = 1;
        
        // Apply where conditions using Hasura v2 boolean expressions
        if let Some(ref where_clause) = where_ {{
            let (where_sql, where_params) = self.build_bool_exp_sql(where_clause, &mut param_count)?;
            if !where_sql.is_empty() {{
                query.push_str(&format!(" WHERE {{}}", where_sql));
                params.extend(where_params);
            }}
        }}
        
        // Apply ordering
        if let Some(ref order_by_clause) = order_by {{
            let order_sql = self.build_order_by_sql(order_by_clause)?;
            if !order_sql.is_empty() {{
                query.push_str(&format!(" ORDER BY {{}}", order_sql));
            }}
        }}
        
        // Apply pagination
        if let Some(limit_val) = limit {{
            query.push_str(&format!(" LIMIT {{}}", limit_val));
        }}
        
        if let Some(offset_val) = offset {{
            query.push_str(&format!(" OFFSET {{}}", offset_val));
        }}
        
        // Execute query
        let mut query_builder = sqlx::query_as::<_, {model_name}Row>(&query);
        
        // Bind parameters
        let rows = query_builder.fetch_all(pool).await?;
        
        // Convert to GraphQL models
        let entities: Vec<{model_name}> = rows.into_iter().map(|row| row.into()).collect();
        
        Ok(entities)
    }}

"#,
            model_name = model_name,
            model_lower = model_lower,
            table_name = table_name,
        ))
    }
    
