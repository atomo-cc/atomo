    /// Generate aggregate query following Hasura v2 conventions
    fn generate_aggregate_query(&self, model: &Model) -> Result<String> {
        let model_name = &model.name;
        let model_lower = model_name.to_lowercase();
        let table_name = format!("{}s", model_lower);
        
        Ok(format!(
            r#"    /// Query {table_name} aggregate with count and statistics
    async fn {table_name}_aggregate(
        &self,
        ctx: &Context<'_>,
        where_: Option<{model_name}BoolExp>,
        order_by: Option<Vec<{model_name}OrderBy>>,
        limit: Option<i32>,
        offset: Option<i32>,
        distinct_on: Option<Vec<{model_name}SelectColumn>>,
    ) -> FieldResult<{model_name}Aggregate> {{
        let pool = ctx.data::<PgPool>()?;
        
        // Build count query
        let mut count_query = format!("SELECT COUNT(*) as count FROM {model_lower}");
        let mut param_count = 1;
        
        // Apply where conditions
        if let Some(ref where_clause) = where_ {{
            let (where_sql, _) = self.build_bool_exp_sql(where_clause, &mut param_count)?;
            if !where_sql.is_empty() {{
                count_query.push_str(&format!(" WHERE {{}}", where_sql));
            }}
        }}
        
        // Get count
        let count_row: (i64,) = sqlx::query_as(&count_query)
            .fetch_one(pool)
            .await?;
        
        // Get nodes if requested
        let nodes = if limit.unwrap_or(0) > 0 {{
            self.{table_name}(ctx, where_, order_by, limit, offset, distinct_on).await?
        }} else {{
            Vec::new()
        }};
        
        Ok({model_name}Aggregate {{
            aggregate: Some({model_name}AggregateFields {{
                count: Some(count_row.0 as i32),
            }}),
            nodes,
        }})
    }}

"#,
            model_name = model_name,
            model_lower = model_lower,
            table_name = table_name,
        ))
    }
    
