    /// Generate insert_one mutation following Hasura v2 conventions using sqlx::QueryBuilder
    fn generate_insert_one_mutation(&self, model: &Model) -> Result<String> {
        let model_name = &model.name;
        let model_lower = model_name.to_lowercase();

        // Generate field mappings for the insert query
        let mut field_mappings = Vec::new();
        let mut field_bindings = Vec::new();

        // Add required fields
        field_mappings.push("id".to_string());
        field_mappings.push("created_at".to_string());
        field_mappings.push("updated_at".to_string());

        // Process model fields
        for (field_name, field) in &model.fields {
            if field_name == "id"
                || field_name == "createdAt"
                || field_name == "updatedAt"
                || field_name == "version"
            {
                continue;
            }

            let db_field_name = self.camel_to_snake_case(field_name);
            let struct_field_name = self.camel_to_snake_case(field_name);
            field_mappings.push(db_field_name.clone());

            let ident = safe_ident(field_name);
            let struct_ident = safe_ident(&struct_field_name);

            // Generate field binding logic
            let field_binding = if !field.optional {
                // Required field - provide default if None
                match &field.field_type {
                    crate::types::FieldType::String => {
                        format!(
                            "let {} = object.{}.unwrap_or_else(|| \"\".to_string());",
                            ident, struct_ident
                        )
                    }
                    crate::types::FieldType::Array(inner) => {
                        // Check if this array will be converted to JSON in type generation
                        match inner.as_ref() {
                            crate::types::FieldType::Custom(name) if name.contains("Block") => {
                                format!("let {} = object.{}.unwrap_or_else(|| serde_json::Value::Array(Vec::new()));", ident, struct_ident)
                            }
                            _ => {
                                format!(
                                    r#"let {} = object.{}.unwrap_or_else(|| Vec::new());
        let {}_json = serde_json::to_value(&{})?;"#,
                                    ident, struct_ident, field_name, ident
                                )
                            }
                        }
                    }
                    crate::types::FieldType::Json => {
                        format!(
                            "let {} = object.{}.unwrap_or_else(|| serde_json::json!({{}}));",
                            ident, struct_ident
                        )
                    }
                    _ => {
                        format!(
                            "let {} = object.{}.unwrap_or_default();",
                            ident, struct_ident
                        )
                    }
                }
            } else {
                // Optional field
                format!("let {} = object.{};", ident, struct_ident)
            };

            field_bindings.push((field_binding, field_name.clone(), field.clone()));
        }

        // Generate the field bindings code
        let mut binding_code = String::new();
        let mut bind_fields = Vec::new();

        for (binding, field_name, field) in &field_bindings {
            binding_code.push_str("        ");
            binding_code.push_str(binding);
            binding_code.push('\n');

            let ident = safe_ident(field_name);
            // Add to bind fields
            match &field.field_type {
                crate::types::FieldType::Array(inner) => {
                    match inner.as_ref() {
                        crate::types::FieldType::Custom(name) if name.contains("Block") => {
                            bind_fields.push(ident);
                        }
                        _ => {
                            bind_fields.push(format!("{}_json", field_name));
                        }
                    }
                }
                _ => {
                    bind_fields.push(ident);
                }
            }
        }

        let fields_str = field_mappings.join(", ");

        // Create query builder code for inserting
        let mut query_builder_code = String::new();
        query_builder_code.push_str(&format!("        let mut query_builder = sqlx::QueryBuilder::<sqlx::Postgres>::new(\"INSERT INTO {} ({})\");\n", model_lower, fields_str));
        query_builder_code.push_str("        query_builder.push_values([1], |mut b, _| {\n");
        query_builder_code.push_str("            b.push_bind(&id)\n");
        query_builder_code.push_str("             .push_bind(&now)\n");
        query_builder_code.push_str("             .push_bind(&now)");

        for field_name in &bind_fields {
            query_builder_code.push_str(&format!("\n             .push_bind(&{})", field_name));
        }

        query_builder_code.push_str(";\n        });\n");
        query_builder_code.push_str("        query_builder.push(\" RETURNING *\");\n");

        Ok(format!(
            r#"    /// Insert a single {model_lower} using QueryBuilder
    async fn insert_{model_lower}_one(
        &self,
        ctx: &Context<'_>,
        object: {model_name}InsertInput,
        on_conflict: Option<{model_name}OnConflict>,
    ) -> FieldResult<Option<{model_name}>> {{
        let pool = ctx.data::<PgPool>()?;
        
        // Generate UUID for new record
        let id = uuid::Uuid::new_v4().to_string();
        let now = chrono::Utc::now();
        
        // Process input fields
{binding_code}
        
        // Build insert query using QueryBuilder
{query_builder_code}
        
        // Execute insert
        let query = query_builder.build_query_as::<{model_name}Row>();
        let row = query.fetch_one(pool).await?;
        
        Ok(Some(row.into()))
    }}

"#,
            model_name = model_name,
            model_lower = model_lower,
            binding_code = binding_code,
            query_builder_code = query_builder_code,
        ))
    }

